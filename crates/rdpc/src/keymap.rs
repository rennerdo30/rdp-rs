//! minifb key to PC/AT set-1 scancode (with E0 "extended" flag).

use minifb::Key;

pub fn scancode(key: Key) -> Option<(u8, bool)> {
    use Key::*;
    let (code, ext) = match key {
        Escape => (0x01, false),
        Key1 => (0x02, false),
        Key2 => (0x03, false),
        Key3 => (0x04, false),
        Key4 => (0x05, false),
        Key5 => (0x06, false),
        Key6 => (0x07, false),
        Key7 => (0x08, false),
        Key8 => (0x09, false),
        Key9 => (0x0A, false),
        Key0 => (0x0B, false),
        Minus => (0x0C, false),
        Equal => (0x0D, false),
        Backspace => (0x0E, false),
        Tab => (0x0F, false),
        Q => (0x10, false),
        W => (0x11, false),
        E => (0x12, false),
        R => (0x13, false),
        T => (0x14, false),
        Y => (0x15, false),
        U => (0x16, false),
        I => (0x17, false),
        O => (0x18, false),
        P => (0x19, false),
        LeftBracket => (0x1A, false),
        RightBracket => (0x1B, false),
        Enter => (0x1C, false),
        LeftCtrl => (0x1D, false),
        A => (0x1E, false),
        S => (0x1F, false),
        D => (0x20, false),
        F => (0x21, false),
        G => (0x22, false),
        H => (0x23, false),
        J => (0x24, false),
        K => (0x25, false),
        L => (0x26, false),
        Semicolon => (0x27, false),
        Apostrophe => (0x28, false),
        Backquote => (0x29, false),
        LeftShift => (0x2A, false),
        Backslash => (0x2B, false),
        Z => (0x2C, false),
        X => (0x2D, false),
        C => (0x2E, false),
        V => (0x2F, false),
        B => (0x30, false),
        N => (0x31, false),
        M => (0x32, false),
        Comma => (0x33, false),
        Period => (0x34, false),
        Slash => (0x35, false),
        RightShift => (0x36, false),
        NumPadAsterisk => (0x37, false),
        LeftAlt => (0x38, false),
        Space => (0x39, false),
        CapsLock => (0x3A, false),
        F1 => (0x3B, false),
        F2 => (0x3C, false),
        F3 => (0x3D, false),
        F4 => (0x3E, false),
        F5 => (0x3F, false),
        F6 => (0x40, false),
        F7 => (0x41, false),
        F8 => (0x42, false),
        F9 => (0x43, false),
        F10 => (0x44, false),
        NumLock => (0x45, false),
        ScrollLock => (0x46, false),
        NumPad7 => (0x47, false),
        NumPad8 => (0x48, false),
        NumPad9 => (0x49, false),
        NumPadMinus => (0x4A, false),
        NumPad4 => (0x4B, false),
        NumPad5 => (0x4C, false),
        NumPad6 => (0x4D, false),
        NumPadPlus => (0x4E, false),
        NumPad1 => (0x4F, false),
        NumPad2 => (0x50, false),
        NumPad3 => (0x51, false),
        NumPad0 => (0x52, false),
        NumPadDot => (0x53, false),
        F11 => (0x57, false),
        F12 => (0x58, false),
        NumPadEnter => (0x1C, true),
        RightCtrl => (0x1D, true),
        NumPadSlash => (0x35, true),
        RightAlt => (0x38, true),
        Home => (0x47, true),
        Up => (0x48, true),
        PageUp => (0x49, true),
        Left => (0x4B, true),
        Right => (0x4D, true),
        End => (0x4F, true),
        Down => (0x50, true),
        PageDown => (0x51, true),
        Insert => (0x52, true),
        Delete => (0x53, true),
        LeftSuper => (0x5B, true),
        RightSuper => (0x5C, true),
        Menu => (0x5D, true),
        _ => return None,
    };
    Some((code, ext))
}
